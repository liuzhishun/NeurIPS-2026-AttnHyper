import os
import argparse
import json

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
from tqdm import tqdm


def calculate_hallucination_spans(labels, text, response_rag, tokenizer, end_inclusive=False):
    """Map char-level hallucination spans in the response to token-level spans in the full input.

    labels: list of dicts with 'start'/'end' char offsets relative to response_rag
    text: prompt after tokenizer.apply_chat_template(...)
    end_inclusive: if True, label['end'] is an inclusive char index; if False, exclusive
    returns: list of [token_start, token_end) positions in the concatenated input
    """
    rag_enc = tokenizer(response_rag, return_offsets_mapping=True, add_special_tokens=False)
    offsets = rag_enc["offset_mapping"]  # (char_start, char_end) per response token, char_end exclusive

    prefix_enc = tokenizer(text, add_special_tokens=False)
    prefix_len = len(prefix_enc["input_ids"])

    spans = []
    for item in labels:
        char_s = item["start"]
        char_e = item["end"]
        if end_inclusive:
            char_e = char_e + 1

        token_s = None
        token_e = None  # exclusive
        for idx, (s, e) in enumerate(offsets):
            if token_s is None and s <= char_s < e:
                token_s = idx
            if token_s is not None and s < char_e <= e:
                token_e = idx + 1
                break

        # char_e falls on a token boundary: extend to the token covering it
        if token_s is not None and token_e is None:
            for j in range(token_s, len(offsets)):
                s, e = offsets[j]
                if e >= char_e:
                    token_e = j + 1
                    break
            if token_e is None:
                token_e = len(offsets)

        if token_s is None:
            continue

        spans.append([prefix_len + token_s, prefix_len + token_e])

    return spans


def get_token_hallucination_labels(seq_len, hallucination_spans):
    """Build a 0/1 label list of length seq_len from token-level [start, end) spans."""
    labels = [0] * seq_len
    for s, e in hallucination_spans:
        s = max(0, s)
        e = min(seq_len, e)
        for i in range(s, e):
            labels[i] = 1
    return labels


parser = argparse.ArgumentParser(description="Extract LLM attention for RAGTruth samples")
parser.add_argument("--model_path", type=str, default="../../models/llama-2-7b-chat-hf",
                    help="local model path; its directory name is used as the save subdirectory")
parser.add_argument("--split", type=str, default="test", choices=["train", "test"])
parser.add_argument("--task_type", type=str, default="Data2txt", choices=["QA", "Summary", "Data2txt"])
parser.add_argument("--data_dir", type=str, default="../../datasets/RAGTruth")
parser.add_argument("--out_root", type=str, default="attention_hidden_data/RAGtruth")
args = parser.parse_args()

model_name = args.model_path
# RAGTruth responses come from only two generators; any other local model
# falls back to responses generated by llama-2-7b-chat.
model_key = os.path.basename(os.path.normpath(model_name)).lower()
if "mistral" in model_key:
    data_model = "mistral-7B-instruct"
else:
    data_model = "llama-2-7b-chat"

response_path = f"{args.data_dir}/response.jsonl"
source_info_path = f"{args.data_dir}/source_info.jsonl"

response = []
source_info_dict = {}
with open(response_path, "r") as f:
    for line in f:
        data = json.loads(line)
        response.append(data)

with open(source_info_path, "r") as f:
    for line in f:
        data = json.loads(line)
        source_info_dict[data["source_id"]] = data

model = AutoModelForCausalLM.from_pretrained(
    model_name,
    device_map="auto",
    torch_dtype=torch.float16
)
tokenizer = AutoTokenizer.from_pretrained(model_name)
device = "cuda:0"
data_len = 0

model_tag = os.path.basename(os.path.normpath(model_name))
split_type = args.split
task_type = args.task_type
save_dir = f"{args.out_root}/{model_tag}/{split_type}_{task_type}"
os.makedirs(save_dir, exist_ok=True)
print(f"Starting extract {model_tag} {split_type}_{task_type} (data_model={data_model}) ......")

for i in tqdm(range(len(response)), desc="Data processing"):
    if response[i]["model"] == data_model and response[i]["split"] == split_type:
        response_rag = response[i]["response"]
        source_id = response[i]["source_id"]
        if source_info_dict[source_id]["task_type"] == task_type:
            data_len += 1
            save_path = f"{save_dir}/sample_{data_len}.pt"

            prompt = source_info_dict[source_id]["prompt"]
            messages = [
                {"role": "system", "content": "You are a helpful assistant."},
                {"role": "user", "content": prompt}
            ]
            text = tokenizer.apply_chat_template(
                messages,
                tokenize=False,
                add_generation_prompt=True
            )
            input_text = text + response_rag

            input_ids = tokenizer([input_text], return_tensors="pt").input_ids.to(device)
            prefix_ids = tokenizer([text], return_tensors="pt").input_ids.to(device)

            if "labels" in response[i].keys():
                hallucination_spans = calculate_hallucination_spans(
                    response[i]["labels"], text, response_rag, tokenizer
                )
            else:
                hallucination_spans = []
            hallucination_labels = get_token_hallucination_labels(
                seq_len=input_ids.shape[-1],
                hallucination_spans=hallucination_spans
            )

            with torch.no_grad():
                outputs = model(
                    input_ids=input_ids,
                    return_dict=True,
                    output_attentions=True,
                    output_hidden_states=False
                )
            all_attentions = torch.stack(
                [att.squeeze(0).cpu() for att in outputs.attentions],
                dim=0
            )
            response_idx = prefix_ids.shape[-1]

            save_obj = {
                "source_id": source_id,
                "response_idx": response_idx,
                "token_ids": input_ids.squeeze(0).cpu(),      # (seq,)
                "attention": all_attentions,                  # (layers, heads, seq, seq)
                "hallucination_labels": hallucination_labels,
                "original_idx": i,
            }
            torch.save(save_obj, save_path)
            torch.cuda.empty_cache()

print(f"Saved {data_len} samples to {save_dir}")
